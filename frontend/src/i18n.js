const LangCtx = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("sf_lang") || "hinglish");
  useEffect(() => { localStorage.setItem("sf_lang", lang); }, [lang]);
  const t = (k) => (STR[lang] && STR[lang][k]) || STR.english[k] || k;
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() { return useContext(LangCtx); }

// The public home page is always in English; the language setting is for the admin app.
const tEnglish = (k) => STR.english[k] || k;
export function useEnglish() { return { t: tEnglish, lang: "english" }; }

